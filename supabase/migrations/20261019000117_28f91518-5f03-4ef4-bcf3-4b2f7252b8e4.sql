INSERT INTO public.categorias_servicos (nome,descricao,sigla)
SELECT DISTINCT i.categoria,i.categoria, CASE WHEN i.categoria LIKE '% - %' THEN split_part(i.categoria,' - ',1) ELSE NULL END
FROM import_servicos_planilha i
WHERE NOT EXISTS (SELECT 1 FROM public.categorias_servicos c WHERE upper(btrim(c.nome))=upper(btrim(i.categoria)));

DO $$ BEGIN
IF EXISTS (SELECT 1 FROM import_servicos_planilha i WHERE (SELECT count(*) FROM public.categorias_servicos c WHERE upper(btrim(c.nome))=upper(btrim(i.categoria))) <> 1) THEN
RAISE EXCEPTION 'Categoria ausente ou ambígua; importação cancelada';
END IF;
END $$;

INSERT INTO public.servicos (nome,descricao,categoria_id)
SELECT DISTINCT i.nome,i.nome,c.id
FROM import_servicos_planilha i
JOIN public.categorias_servicos c ON upper(btrim(c.nome))=upper(btrim(i.categoria))
WHERE NOT EXISTS (SELECT 1 FROM public.servicos s WHERE s.categoria_id=c.id AND upper(regexp_replace(btrim(s.nome),'\s+',' ','g'))=upper(regexp_replace(btrim(i.nome),'\s+',' ','g')));

DO $$ BEGIN
IF EXISTS (SELECT 1 FROM import_servicos_planilha i JOIN public.categorias_servicos c ON upper(btrim(c.nome))=upper(btrim(i.categoria)) WHERE NOT EXISTS (SELECT 1 FROM public.servicos s WHERE s.categoria_id=c.id AND s.nome=i.nome)) THEN
RAISE EXCEPTION 'Serviço não importado; operação cancelada';
END IF;
END $$;